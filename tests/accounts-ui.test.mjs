import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const [api,main,account,css]=await Promise.all(['app/explore/api.js','app/explore/main.js','app/account.js','app/account.css'].map(p=>readFile(new URL(p,root),'utf8')));
// Execute API code with a controlled transport; no browser or real credential.
const source=api.replace("import {errorInfo} from '/presentation.js';",'const errorInfo=e=>({message:e.message,code:e.code,retryable:e.retryable});');
const module=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
let seen,expired=0;
globalThis.window={dispatchEvent:()=>expired++};
globalThis.fetch=async(path,options)=>{seen={path,options};return {ok:true,json:async()=>({ok:true})};};
module.setCSRF('fixture-csrf');await module.request('/api/account/preferences',{enabled:false});
assert.equal(seen.options.headers['X-BNU-CSRF'],'fixture-csrf');
assert.equal(seen.options.credentials,'same-origin');
assert.doesNotMatch(seen.options.body,/fixture-csrf/,'CSRF stays out of persisted business payload');
globalThis.fetch=async()=>({ok:false,json:async()=>({error:'请登录',code:'AUTH_REQUIRED',retryable:false})});
await assert.rejects(module.request('/api/account/conversations'),/请登录/);assert.equal(expired,1);
module.setCSRF('');globalThis.fetch=async(path,options)=>{seen=options;return {ok:true,json:async()=>({})};};
await module.request('/api/account/login',{});assert.equal(seen.headers['X-BNU-CSRF'],'');
assert.match(main,/await account.init\(\);\s*if\(!account.enabled\)try\{db=await openHistory/,'No anonymous history opened in account mode');
assert.doesNotMatch(main,/^import .*from '\/account.js'/m,'Old running service must not require a new static route');
assert.match(main,/response.status===404/,'Explicit missing account endpoint permits legacy preview');
assert.match(main,/status.enabled!==true/,'Invalid account status must fail closed');
assert.match(main,/epoch!==identityEpoch/,'Discard stale stream on identity change');
assert.match(main,/if\(epoch===identityEpoch\)/,'Discard stale completion on identity change');
assert.match(account,/channel.onmessage=reset/,'Other tabs clear private data after login/logout');
assert.doesNotMatch(account,/localStorage|innerHTML|insertAdjacentHTML/);
assert.match(account,/dialog.showModal\(\)/,'Native modal supplies focus containment');
assert.match(css,/#account-entry:not\(\[hidden\]\)/,'Mobile account access remains visible');
console.log('accounts-ui: transport CSRF, auth expiry, private history boundary, identity guards and mobile entry passed');
