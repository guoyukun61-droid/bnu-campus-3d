import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {GROUPS,filterPlaces,inModel,positionNote,reduceState,selectionIds,easeCamera,shouldRoam} from '../app/explore/state.js';
const rows=[{id:'a',name:'餐厅',address:'校园',display_category:'food',location:{x:1,y:2}},{id:'b',name:'瑞幸',address:'二层',display_category:'drinks',location:null,display_anchor:{x:3,y:4}},{id:'c',name:'馆',address:'校外',display_category:'sports',location:{x:800,y:1}},{id:'d',name:'店',address:'西侧',location:null,map_reference:{x:1,y:2}}];
assert.equal(GROUPS.length,7);
assert.deepEqual(filterPlaces(rows,'food').map(p=>p.id),['a']);
assert.deepEqual(filterPlaces(rows,'','二层').map(p=>p.id),['b']);
assert.equal(inModel(rows[1]),true);assert.equal(rows[1].location,null);
assert.equal(inModel(rows[2]),false);assert.equal(inModel(rows[3]),false);
assert.match(positionNote(rows[1]),/楼栋/);assert.match(positionNote(rows[3]),/参照/);
let s={panel:'chat',category:'',selected:'a'};
s=reduceState(s,{type:'category',value:'drinks'});assert.equal(s.panel,'list');assert.equal(s.selected,null);
s=reduceState(s,{type:'select',id:'b'});assert.equal(s.panel,'detail');assert.equal(s.selected,'b');
s=reduceState(s,{type:'close'});assert.equal(s.panel,null);
assert.deepEqual(selectionIds([{poi_id:'a'},{id:'a'},{id:'not-real'}],rows),['a']);
assert.equal(easeCamera(0),0);assert.equal(easeCamera(1),1);assert.equal(easeCamera(-10),0);assert.equal(easeCamera(10),1);
const css=await readFile(new URL('../app/explore/explore.css',import.meta.url),'utf8');
assert.match(css,/prefers-reduced-motion/);assert.doesNotMatch(css,/transition\s*:\s*all/);
const main=await readFile(new URL('../app/explore/main.js',import.meta.url),'utf8');
assert.match(main,/detailsToken/);assert.match(main,/controller.abort/);
const scene=await readFile(new URL('../app/explore/scene.js',import.meta.url),'utf8');
assert.match(scene,/controls.addEventListener\('start'.*tween=null/);
assert.match(scene,/document.hidden/);
assert.equal(GROUPS[0][1],'建筑');
assert.equal(shouldRoam(true,false,false,false),true);
for(const conditions of [[false,false,false,false],[true,true,false,false],[true,false,true,false],[true,false,false,true]])assert.equal(shouldRoam(...conditions),false);
assert.match(scene,/if\(!visibleIds\)\{onBuilding\(id\)/);
assert.match(scene,/p.visible=!!visibleIds/);
console.log('explore: 33 assertions passed');
